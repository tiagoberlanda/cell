# Lets agents reach folders on this computer: mounts the local drives into the worker (C: only the user's profile
# folder; other fixed local drives whole). Agents still need the owner's approval for each folder they use.
# Writes compose.override.yaml (machine-specific, loaded automatically by docker compose). -Remove turns it off.
param([switch]$Remove)
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path $PSScriptRoot -Parent)
$file = 'compose.override.yaml'
if ($Remove) { Remove-Item $file -ErrorAction SilentlyContinue; Write-Host 'Acesso aos discos removido. Rode ./scripts/deploy.ps1 para aplicar.'; return }
$mounts = @()
foreach ($disk in Get-CimInstance Win32_LogicalDisk -Filter 'DriveType=3') {
    $letter = $disk.DeviceID.Substring(0, 1).ToUpper()
    if ($letter -eq 'C') {
        $source = $env:USERPROFILE
        $target = '/host/c/' + ($env:USERPROFILE.Substring(3) -replace '\\', '/')
    } else {
        $source = "${letter}:\"
        $target = '/host/' + $letter.ToLower()
    }
    $mounts += "      - type: bind`n        source: '$source'`n        target: $target"
}
$yaml = "# Generated by scripts/drives.ps1 on this machine. Not committed.`nservices:`n  worker:`n    volumes:`n" + ($mounts -join "`n") + "`n"
[IO.File]::WriteAllText((Join-Path (Get-Location) $file), $yaml)
Write-Host "Discos liberados para o worker:"; $mounts | ForEach-Object { ($_ -split "`n")[1].Trim() }
Write-Host 'Rode ./scripts/deploy.ps1 para aplicar.'
